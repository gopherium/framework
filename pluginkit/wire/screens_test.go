func TestGenerateScreensUsesTSLicenseWhenSet(t *testing.T) {
	t.Parallel()

	cfg := testConfig
	cfg.TSLicense = "AGPL-3.0-or-later"

	got := string(generateScreens(cfg, nil))

	if want := "// SPDX-License-Identifier: AGPL-3.0-or-later\n"; got[:len(want)] != want {
		t.Errorf("generateScreens() header = %q, want the TSLicense field %q", got[:len(want)], want)
	}
}

func TestGenerateScreensWritesEachAddressAsAStringLiteral(t *testing.T) {
	t.Parallel()

	got := string(generateScreens(testConfig, []manifest{
		{ID: "events", Name: "Events", Backend: "a", Screens: "./a'b\"c\\d\ne\U00002028f</script>&"},
	}))

	want := "\t\"events\": () => import(\"./a'b\\\"c\\\\d\\ne\\u2028f</script>&\"),\n"
	if !strings.Contains(got, want) {
		t.Errorf("generateScreens() = %q, want it to hold %q", got, want)
	}
}

func TestRunWritesTheScreensMapBesideEveryOtherOutput(t *testing.T) {
	t.Parallel()

	feed := withKeys(feedManifest, `"screens": "@myapp/plugin-feed/screens"`)
	for name, cfg := range everySwitchToday() {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			on := withScreens(cfg)
			root := wiringTree(t, on, map[string]string{"feed": feed})

			if err := Run(root, on); err != nil {
				t.Fatalf("Run() error = %v, want nil", err)
			}

			files := generatedFiles(t, root)
			want := "\t\"feed\": () => import(\"@myapp/plugin-feed/screens\"),\n"
			if !strings.Contains(files[screensPath], want) {
				t.Errorf("%s = %q, want it to hold %q", screensPath, files[screensPath], want)
			}
			delete(files, screensPath)
			assertSameFiles(t, files, generate(t, cfg, map[string]string{"feed": feed}))
		})
	}
}

