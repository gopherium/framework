// screensPath is where these tests ask for the lazy screens map.
const screensPath = "frontend/src/plugins/screens.ts"

// withScreens returns cfg with the lazy screens map switched on.
func withScreens(cfg Config) Config {
	cfg.TSScreensPath = screensPath
	return cfg
}

func TestGenerateScreensMapsEachPluginInWiringOrder(t *testing.T) {
	t.Parallel()

	got := string(generateScreens(testConfig, []manifest{
		{ID: "gallery", Name: "Gallery", Frontend: "@myapp/plugin-gallery", Screens: "@myapp/plugin-gallery/screens"},
		{ID: "billing", Name: "Billing", Backend: "example.com/billing"},
		{ID: "events", Name: "Events", Backend: "example.com/events", Screens: "@myapp/plugin-events/screens"},
	}))

	want := `// SPDX-License-Identifier: Apache-2.0

// Code generated by pluginwire. DO NOT EDIT.

export const screens: Readonly<Record<string, () => Promise<unknown>>> = {
	"gallery": () => import("@myapp/plugin-gallery/screens"),
	"events": () => import("@myapp/plugin-events/screens"),
}
`
	if got != want {
		t.Errorf("generateScreens() = %q, want %q", got, want)
	}
}

