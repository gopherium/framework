// withRegistrationList returns cfg with the registration list switched on.
func withRegistrationList(cfg Config) Config {
	cfg.RegistrationList = true
	return cfg
}

// listedManifests are two backend plugins, one with a hyphen in its id, and one plugin with only a frontend.
func listedManifests() []manifest {
	return []manifest{
		{ID: "events", Name: "Events", Backend: "example.com/myapp/plugins/events"},
		{ID: "pretty", Name: "Pretty", Frontend: "@myapp/plugin-pretty"},
		{ID: "photo-gallery", Name: "Photo Gallery", Backend: "example.com/gallery", Frontend: "@myapp/plugin-gallery"},
	}
}

// listedEntries is the list body of listedManifests.
const listedEntries = `	{ID: "events", Register: func(deps sdk.Deps) (sdk.Plugin, error) {
		plugin, err := events.Register(deps)
		if err != nil {
			return nil, err
		}
		return plugin, nil
	}},
	{ID: "photo-gallery", Register: func(deps sdk.Deps) (sdk.Plugin, error) {
		plugin, err := photo_gallery.Register(deps)
		if err != nil {
			return nil, err
		}
		return plugin, nil
	}},
`

// listedFile is the generated file of listedManifests in package pkg, its list in the variable name.
func listedFile(pkg, name string) string {
	return "// SPDX-License-Identifier: Apache-2.0\n\n// Code generated by pluginwire. DO NOT EDIT.\n\npackage " + pkg +
		"\n\nimport (\n\tphoto_gallery \"example.com/gallery\"\n\tevents \"example.com/myapp/plugins/events\"\n\n" +
		"\tpluginKit \"github.com/gopherium/framework/pluginkit\"\n\n\tsdk \"example.com/myapp/sdk\"\n)\n\n" +
		"// " + name + " lists every compiled backend plugin's manifest id and Register function, in wiring order.\n" +
		"var " + name + " = []pluginKit.Registration[sdk.Deps, sdk.Plugin]{\n" + listedEntries + "}\n"
}

func TestGenerateWritesARegistrationListOfEveryBackendInWiringOrder(t *testing.T) {
	t.Parallel()

	cfg := withRegistrationList(testConfig)
	cfg.GoRegistryPackage = "graphroot"
	tests := map[string]struct{ got, want string }{
		"the main file": {string(generateGo(cfg, listedManifests())), listedFile("main", "pluginRegistrations")},
		"the registry":  {string(generateRegistry(cfg, listedManifests())), listedFile("graphroot", "Registrations")},
	}
	for name, tc := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			if tc.got != tc.want {
				t.Errorf("generated = %q, want %q", tc.got, tc.want)
			}
		})
	}
}

func TestGenerateGoWritesAnEmptyRegistrationListWithoutBackendPlugins(t *testing.T) {
	t.Parallel()

	got := string(generateGo(withRegistrationList(testConfig), []manifest{
		{ID: "pretty", Name: "Pretty", Frontend: "@myapp/plugin-pretty"},
	}))

	want := `// SPDX-License-Identifier: Apache-2.0

// Code generated by pluginwire. DO NOT EDIT.

package main

import (
	pluginKit "github.com/gopherium/framework/pluginkit"

	sdk "example.com/myapp/sdk"
)

// pluginRegistrations lists every compiled backend plugin's manifest id and Register function, in wiring order.
var pluginRegistrations = []pluginKit.Registration[sdk.Deps, sdk.Plugin]{}
`
	if got != want {
		t.Errorf("generateGo() = %q, want %q", got, want)
	}
}

func TestGeneratedRegistrationListsAreFormattedAsGofmtFormatsThem(t *testing.T) {
	t.Parallel()

	cfg := withRegistrationList(testConfig)
	cfg.GoRegistryPackage = "graphroot"
	files := map[string][]byte{
		"a list":       generateGo(cfg, listedManifests()),
		"an empty one": generateGo(cfg, nil),
		"a registry":   generateRegistry(cfg, listedManifests()),
	}
	for name, src := range files {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			formatted, err := format.Source(src)
			if err != nil || string(formatted) != string(src) {
				t.Errorf("format.Source() = %q, %v, want the source unchanged", formatted, err)
			}
		})
	}
}

func TestRunWritesTheRegistrationListInPlaceOfBothFunctions(t *testing.T) {
	t.Parallel()

	cfg := withRegistrationList(testConfig)
	cfg.GoRegistryPath = "internal/graphroot/registry_gen.go"
	cfg.GoRegistryPackage = "graphroot"

	files := generate(t, cfg, map[string]string{"feed": feedManifest})

	checks := map[string][2]string{
		cfg.GoWiringPath:   {"var pluginRegistrations = ", "func registerPlugins("},
		cfg.GoRegistryPath: {"var Registrations = ", "func All("},
	}
	for path, check := range checks {
		if !strings.Contains(files[path], check[0]) || strings.Contains(files[path], check[1]) {
			t.Errorf("%s = %q, want %q in place of %q", path, files[path], check[0], check[1])
		}
	}
}
