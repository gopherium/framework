var testConfig = Config{
	SDKImport:    "example.com/myapp/sdk",
	FrontendSDK:  "@myapp/frontend-sdk",
	GoWiringPath: "cmd/myapp/plugins_gen.go",
	TSWiringPath: "frontend/src/plugins/index.ts",
	License:      "Apache-2.0",
}

const feedManifest = `{
	"id": "feed",
	"name": "Feed",
	"backend": "example.com/myapp/plugins/feed",
	"frontend": "@myapp/plugin-feed"
}`

func writePlugin(t *testing.T, root, dir, manifestJSON string) {
	t.Helper()
	writePluginIn(t, root, "plugins", dir, manifestJSON)
}

func writePluginIn(t *testing.T, root, pluginRoot, dir, manifestJSON string) {
	t.Helper()
	pluginDir := filepath.Join(root, pluginRoot, dir)
	if err := os.MkdirAll(pluginDir, 0o755); err != nil {
		t.Fatalf("creating %s: %v", pluginDir, err)
	}
	if manifestJSON == "" {
		return
	}
	if err := os.WriteFile(filepath.Join(pluginDir, "plugin.json"), []byte(manifestJSON), 0o644); err != nil {
		t.Fatalf("writing manifest: %v", err)
	}
}

func TestLoadManifestsReadsValidPlugins(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	writePlugin(t, root, "photo-gallery",
		`{"id": "photo-gallery", "name": "Photo Gallery", "backend": "example.com/gallery"}`)
	writePlugin(t, root, "feed", feedManifest)
	if err := os.WriteFile(filepath.Join(root, "plugins", "README.md"), []byte("not a plugin"), 0o644); err != nil {
		t.Fatalf("writing stray file: %v", err)
	}

	manifests, err := loadManifests(filepath.Join(root, "plugins"))

	if err != nil {
		t.Fatalf("loadManifests() error = %v, want nil", err)
	}
	if len(manifests) != 2 {
		t.Fatalf("manifests = %d, want 2", len(manifests))
	}
	if manifests[0].ID != "feed" || manifests[1].ID != "photo-gallery" {
		t.Errorf("order = [%q, %q], want directory order [%q, %q]",
			manifests[0].ID, manifests[1].ID, "feed", "photo-gallery")
	}
	if manifests[0].Backend != "example.com/myapp/plugins/feed" {
		t.Errorf("backend = %q, want the module import path", manifests[0].Backend)
	}
	if manifests[0].Frontend != "@myapp/plugin-feed" {
		t.Errorf("frontend = %q, want the npm package name", manifests[0].Frontend)
	}
}

