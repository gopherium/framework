func TestGenerateGoWiresBackendPlugins(t *testing.T) {
	t.Parallel()

	got := string(generateGo(testConfig, []manifest{
		{ID: "photo-gallery", Name: "Photo Gallery", Backend: "example.com/gallery"},
		{
			ID:       "feed",
			Name:     "Feed",
			Backend:  "example.com/myapp/plugins/feed",
			Frontend: "@myapp/plugin-feed",
		},
	}))

	want := `// SPDX-License-Identifier: Apache-2.0

// Code generated by pluginwire. DO NOT EDIT.

package main

import (
	"errors"
	"fmt"

	photo_gallery "example.com/gallery"
	feed "example.com/myapp/plugins/feed"

	"example.com/myapp/sdk"
)

// registerPlugins registers every compiled plugin, answering the ones that registered and an error naming each failure.
func registerPlugins(deps sdk.Deps) ([]sdk.Plugin, error) {
	plugins := make([]sdk.Plugin, 0, 2)
	var failed []error
	photo_galleryPlugin, err := photo_gallery.Register(deps)
	if err != nil {
		failed = append(failed, fmt.Errorf("plugin photo-gallery: %w", err))
	} else {
		plugins = append(plugins, photo_galleryPlugin)
	}
	feedPlugin, err := feed.Register(deps)
	if err != nil {
		failed = append(failed, fmt.Errorf("plugin feed: %w", err))
	} else {
		plugins = append(plugins, feedPlugin)
	}
	return plugins, errors.Join(failed...)
}
`
	if got != want {
		t.Errorf("generateGo() = %q, want %q", got, want)
	}
}

