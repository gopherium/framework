func TestRunReportsFailures(t *testing.T) {
	t.Parallel()

	tests := map[string]struct {
		roots       []string
		packageJSON string
		names       string
		prepare     func(t *testing.T, root string)
	}{
		"missing plugins directory": {
			prepare: func(_ *testing.T, _ string) {},
		},
		"missing package.json": {
			packageJSON: "frontend/package.json",
			names:       "frontend/package.json",
			prepare: func(t *testing.T, root string) {
				writePlugin(t, root, "feed", feedManifest)
				makeDirs(t, root, "cmd/myapp", "frontend/src/plugins")
			},
		},
		"missing named root": {
			roots: []string{"plugins", "enterprise"},
			prepare: func(t *testing.T, root string) {
				writePlugin(t, root, "feed", feedManifest)
				for _, dir := range []string{"cmd/myapp", "frontend/src/plugins"} {
					if err := os.MkdirAll(filepath.Join(root, dir), 0o755); err != nil {
						t.Fatalf("creating %s: %v", dir, err)
					}
				}
			},
		},
		"unwritable go wiring": {
			prepare: func(t *testing.T, root string) {
				writePlugin(t, root, "feed", feedManifest)
			},
		},
		"unwritable ts wiring": {
			prepare: func(t *testing.T, root string) {
				writePlugin(t, root, "feed", feedManifest)
				if err := os.MkdirAll(filepath.Join(root, "cmd", "myapp"), 0o755); err != nil {
					t.Fatalf("creating cmd/myapp: %v", err)
				}
			},
		},
	}

	for testName, tc := range tests {
		t.Run(testName, func(t *testing.T) {
			t.Parallel()

			root := t.TempDir()
			tc.prepare(t, root)
			cfg := testConfig
			cfg.Roots = tc.roots
			cfg.PackageJSONPath = tc.packageJSON

			err := Run(root, cfg)

			if err == nil {
				t.Fatal("Run() error = nil, want an error")
			}
			if tc.names == "" {
				return
			}
			want := "pluginwire: " + filepath.Join(root, filepath.FromSlash(tc.names)) + ": "
			if !strings.HasPrefix(err.Error(), want) {
				t.Errorf("Run() error = %q, want it to start with %q", err, want)
			}
		})
	}
}
